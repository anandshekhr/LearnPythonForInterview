"""Lever Postings API (https://github.com/lever/postings-api).

Listing published postings is public. The apply endpoint
(POST /v0/postings/{site}/{id}?key=...) requires an API key generated by the employer's
Lever Super Admin; Lever rate-limits applications to 2 POSTs/second.
"""
from __future__ import annotations

from datetime import datetime, timezone

from apps.core.text import clean_text, html_to_text

from ..normalization import NormalizedJob, Salary, normalize_employment_type
from .base import JobSourceAdapter, SourceCapabilities, SubmissionNotSupported, SubmissionResult

PAGE = 100


def _ms(value):
    if not value:
        return None
    try:
        return datetime.fromtimestamp(int(value) / 1000, tz=timezone.utc)
    except (TypeError, ValueError):
        return None


class LeverAdapter(JobSourceAdapter):
    source_type = "lever"
    allowed_config = {"region": str}
    capabilities = SourceCapabilities(
        salary_data=True,
        application_questions=False,
        api_submission=True,
        api_submission_requires="Postings API key generated by the employer's Lever Super Admin",
        browser_assist=True,
        documentation_url="https://github.com/lever/postings-api",
        limitations=(
            "Only published postings are visible.",
            "Custom application questions are not exposed by the Postings API.",
            "API submission requires the employer's key; otherwise apply on the hosted Lever form.",
        ),
    )

    @property
    def base(self):
        from django.conf import settings

        override = settings.SOURCE_API_BASE_OVERRIDES.get("lever")
        if override:
            return f"{override.rstrip('/')}/{self.identifier}"
        host = "api.eu.lever.co" if self.config.get("region") == "eu" else "api.lever.co"
        return f"https://{host}/v0/postings/{self.identifier}"

    def _job(self, item: dict) -> NormalizedJob:
        cats = item.get("categories") or {}
        parts = [item.get("descriptionPlain") or html_to_text(item.get("description") or "")]
        for lst in item.get("lists") or []:
            parts.append(lst.get("text", ""))
            parts.append(html_to_text(lst.get("content", "")))
        parts.append(item.get("additionalPlain") or html_to_text(item.get("additional") or ""))
        salary = Salary()
        rng = item.get("salaryRange") or {}
        if rng.get("min") and rng.get("max"):
            period = {"per-year-salary": "year", "per-month-salary": "month", "per-hour-wage": "hour"}.get(rng.get("interval", ""), "year")
            salary = Salary(int(rng["min"]), int(rng["max"]), rng.get("currency", ""), period, "")
        locations = cats.get("allLocations") or ([cats["location"]] if cats.get("location") else [])
        workplace = (item.get("workplaceType") or "").lower()
        return NormalizedJob(
            external_id=str(item["id"]),
            title=item.get("text") or "",
            canonical_url=item.get("hostedUrl") or "",
            apply_url=item.get("applyUrl") or item.get("hostedUrl") or "",
            description_text=clean_text("\n\n".join(p for p in parts if p)),
            department=" / ".join(x for x in [cats.get("department"), cats.get("team")] if x),
            location_raw=" / ".join(locations),
            locations=list(locations),
            work_model={"remote": "remote", "hybrid": "hybrid", "on-site": "onsite", "onsite": "onsite"}.get(workplace, "unknown"),
            employment_type=normalize_employment_type(cats.get("commitment") or "", item.get("text", "")),
            salary=salary,
            published_at=_ms(item.get("createdAt")),
            source_updated_at=_ms(item.get("updatedAt")),
            raw_metadata={"country": item.get("country"), "workplaceType": item.get("workplaceType")},
        ).finalize()

    def fetch_listings(self):
        skip = 0
        while True:
            page = self.http.get_json(self.base, params={"mode": "json", "skip": skip, "limit": PAGE})
            if not isinstance(page, list):
                break
            for item in page:
                if item.get("id") and item.get("text"):
                    yield self._job(item)
            if len(page) < PAGE:
                break
            skip += PAGE

    def fetch_job(self, external_id: str):
        from ..http import SourceHTTPError

        try:
            item = self.http.get_json(f"{self.base}/{external_id}", params={"mode": "json"})
        except SourceHTTPError as exc:
            if exc.status_code == 404:
                return None
            raise
        return self._job(item)

    def submit_application(self, external_id: str, payload: dict) -> SubmissionResult:
        if not self.api_key:
            raise SubmissionNotSupported("No Lever Postings API key configured for this site")
        data = {
            "name": f"{payload['first_name']} {payload['last_name']}".strip(), "email": payload["email"],
            "phone": payload.get("phone", ""),
        }
        if payload.get("cover_letter_text"):
            data["comments"] = payload["cover_letter_text"]
        for url in payload.get("urls") or []:
            data[f"urls[{url['label']}]"] = url["url"]
        files = {"resume": (payload["resume_filename"], payload["resume_bytes"], payload.get("resume_content_type", "application/pdf"))}
        response = self.http.request("POST", f"{self.base}/{external_id}", params={"key": self.api_key}, data=data, files=files)
        try:
            body = response.json()
        except ValueError:
            body = {}
        confirmed = response.status_code == 200 and body.get("ok") is True and bool(body.get("applicationId"))
        return SubmissionResult(
            confirmed=confirmed, reference=str(body.get("applicationId") or ""), status_code=response.status_code,
            message=str(body.get("error") or ("Application received" if confirmed else ""))[:300],
            response_excerpt={"ok": body.get("ok"), "applicationId": body.get("applicationId")},
        )
